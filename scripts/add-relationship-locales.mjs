let changed = 0;
for (const [code, messages] of Object.entries(TRANSLATIONS)) {
  const file = `${LOCALES}/${code}.json`;
  const locale = JSON.parse(readFileSync(file, "utf8"));
  for (const [key, english] of Object.entries(ENGLISH)) {
    const value = messages[key] ?? english;
    if (locale[key] === value) {
      continue;
    }
    locale[key] = value;
  }
  // The keys of a locale file are sorted, so that a diff stays small.
  const sorted = Object.fromEntries(
    Object.entries(locale).sort(([left], [right]) =>
      left < right ? -1 : left > right ? 1 : 0,
    ),
  );
  writeFileSync(file, `${JSON.stringify(sorted, null, 2)}\n`, "utf8");
  changed += 1;
}

console.log(`updated ${changed} locale files`);
