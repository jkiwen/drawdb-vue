import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { createEmptyDiagram } from "../models/diagram.ts";
import { toPostgres } from "./postgres.ts";

function makeDiagram() {
  const diagram = createEmptyDiagram({ database: "postgres", title: "blog" });
  diagram.enums.push({
    id: "user_role",
    name: "user_role",
    values: ["admin", "user"],
  });
  diagram.types.push({
    id: "point_type",
    name: "point_type",
    fields: [
      { id: "x", name: "x", type: "INTEGER" },
      { id: "y", name: "y", type: "INTEGER" },
    ],
    comment: "A custom point type",
  });
  diagram.tables.push(
    {
      id: "users",
      name: "users",
      x: 0,
      y: 0,
      logical: { id: "le-users", name: "users", attributes: [] },
      fields: [
        {
          id: "uid",
          name: "id",
          fieldType: { type: "INTEGER" },
          fieldTypeSource: "explicit",
          notNull: true,
          increment: true,
        },
        {
          id: "uname",
          name: "username",
          fieldType: { type: "VARCHAR", length: 255 },
          fieldTypeSource: "explicit",
          notNull: true,
          unique: true,
        },
        {
          id: "uem",
          name: "email",
          fieldType: { type: "VARCHAR", length: 255 },
          fieldTypeSource: "explicit",
        },
        {
          id: "urole",
          name: "role",
          fieldType: { type: "user_role" },
          fieldTypeSource: "explicit",
          default: "user",
        },
        {
          id: "ucredits",
          name: "credits",
          fieldType: { type: "DECIMAL", precision: 10, scale: 2 },
          fieldTypeSource: "explicit",
          default: 0,
        },
        {
          id: "uactive",
          name: "active",
          fieldType: { type: "BOOLEAN" },
          fieldTypeSource: "explicit",
          default: "true",
        },
      ],
      primaryKey: {
        id: "pk_users",
        name: "PK_users",
        logicalName: "PK_users",
        columns: [{ fieldId: "uid" }],
      },
      comment: "User accounts",
      indices: [
        { id: "idx_email", name: "idx_email", unique: false, columns: [{ fieldId: "uem" }] },
      ],
            uniqueKeys: [
        {
          id: "uc_username_email",
          logicalName: "uc_username_email",
          name: "uc_username_email",
          columns: [{ fieldId: "uname" }, { fieldId: "uem" }],
        },
      ],
    },
    {
      id: "posts",
      name: "posts",
      x: 300,
      y: 0,
      logical: { id: "le-posts", name: "posts", attributes: [] },
      fields: [
        {
          id: "pid",
          name: "id",
          fieldType: { type: "BIGINT" },
          fieldTypeSource: "explicit",
          notNull: true,
          increment: true,
        },
        {
          id: "puid",
          name: "user_id",
          fieldType: { type: "INTEGER" },
          fieldTypeSource: "explicit",
          notNull: true,
        },
        {
          id: "ptitle",
          name: "title",
          fieldType: { type: "VARCHAR", length: 200 },
          fieldTypeSource: "explicit",
          notNull: true,
        },
      ],
      primaryKey: {
        id: "pk_posts",
        name: "PK_posts",
        logicalName: "PK_posts",
        columns: [{ fieldId: "pid" }],
      },
    },
  );
  diagram.relationships.push({
    id: "rel_user_posts",
    startTableId: "posts",
    startFieldId: "puid",
    endTableId: "users",
    endFieldId: "uid",
    cardinality: "many_to_one",
    updateConstraint: "CASCADE",
    deleteConstraint: "SET NULL",
  });
  return diagram;
}

describe("toPostgres", () => {
  it("exports CREATE TABLE statements with all field attributes", () => {
    const sql = toPostgres(makeDiagram());
    assert.match(sql, /CREATE TABLE IF NOT EXISTS "users"/);
    assert.match(sql, /"id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY/);
    assert.match(sql, /"username" VARCHAR\(255\) NOT NULL UNIQUE/);
    assert.match(sql, /PRIMARY KEY\("id"\)/);
    assert.match(sql, /"role" user_role DEFAULT 'user'/);
    assert.match(sql, /"credits" DECIMAL\(10,2\) DEFAULT 0/);
    assert.match(sql, /"active" BOOLEAN DEFAULT true/);
  });

  it("exports enums and custom types", () => {
    const sql = toPostgres(makeDiagram());
    assert.match(sql, /CREATE TYPE "user_role" AS ENUM \(\n\t'admin',\n\t'user'\n\);/);
    assert.match(sql, /CREATE TYPE "point_type" AS \(/);
    assert.match(
      sql,
      /COMMENT ON TYPE "point_type" IS 'A custom point type';/,
    );
  });

  it("exports table and column comments", () => {
    const sql = toPostgres(makeDiagram());
    assert.match(sql, /COMMENT ON TABLE "users" IS 'User accounts';/);
  });

  it("exports indices and unique constraints", () => {
    const sql = toPostgres(makeDiagram());
    assert.match(sql, /CREATE INDEX "idx_email"\nON "users" \("email"\);/);
    assert.match(
      sql,
      /CONSTRAINT "uc_username_email" UNIQUE \("username", "email"\)/,
    );
  });

  it("exports ALTER TABLE foreign keys", () => {
    const sql = toPostgres(makeDiagram());
    assert.match(sql, /ALTER TABLE "posts"/);
    assert.match(
      sql,
      /ADD FOREIGN KEY\("user_id"\) REFERENCES "users"\("id"\)\nON UPDATE CASCADE ON DELETE SET NULL;/,
    );
  });

  it("exports views", () => {
    const diagram = makeDiagram();
    diagram.views.push({
      id: "v1",
      name: "user_posts",
      x: 0,
      y: 0,
      baseTableId: "users",
      joins: [
        {
          id: "j1",
          type: "INNER",
          tableId: "posts",
          on: {
            leftTableId: "users",
            leftFieldId: "uid",
            rightFieldId: "puid",
          },
        },
      ],
      columns: [
        { id: "c1", tableId: "users", fieldId: "uname" },
        { id: "c2", tableId: "posts", fieldId: "ptitle", alias: "post_title" },
      ],
    });
    const sql = toPostgres(diagram);
    assert.match(sql, /CREATE OR REPLACE VIEW "user_posts" AS/);
    assert.match(sql, /SELECT\n  "users"."username",\n  "posts"."title" AS "post_title"/);
    assert.match(
      sql,
      /FROM "users"\nINNER JOIN "posts" ON "users"."id" = "posts"."user_id"/,
    );
  });
});
