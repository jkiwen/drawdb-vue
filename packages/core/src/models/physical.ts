import type { Metadata } from "./metadata.ts";

/**
 * The physical type specification stored on a field (spec §3.4).
 * It is stored data, not a derived value (invariant 3).
 */
export interface PhysicalSpec {
  /** The physical type name, e.g. "NVARCHAR2". */
  type: string;
  length?: number;
  precision?: number;
  scale?: number;
  /** unicode / unsigned / autoincrement ... */
  flags?: PhysicalFlags;
  /** True when the physical type is a native user-defined type of the target database (a materialized domain). */
  materialized?: boolean;
}

export type PhysicalFlags = {
  unicode?: boolean;
  unsigned?: boolean;
  autoincrement?: boolean;
};

/**
 * The origin of a physical type, deciding whether a mapping change
 * recomputes it (user ruling Q8, spec §3.4):
 * - mapped   : generated by a DSM mapping → recomputed when the mapping or parameters change
 * - explicit : set by hand → never touched by mapping changes
 * - imported : an existing physical definition from an erwin import → left alone by default, can be converted to mapped in bulk
 */
export type FieldTypeSource = "mapped" | "explicit" | "imported";

/**
 * A physical field (the physical layer, replacing the physical part of the
 * former `Field`, spec §3.4).
 */
export interface PhysicalField {
  id: string;
  /** The physical column name; SQL export uses it. */
  name: string;
  /** The stored physical type specification (not a derived value). */
  fieldType: PhysicalSpec;
  /** The origin marker of the physical type. */
  fieldTypeSource: FieldTypeSource;
  /** The physical layer description (erwin: Field.Comment). */
  comment?: string;
  /** Exists only on the physical layer (import asymmetry marker). */
  physicalOnly?: boolean;
  // —— Constraints and defaults (physical layer, carried over) ——
  /** Initial value; may be a function. */
  default?: string | number | boolean;
  check?: string;
  unique?: boolean;
  nullable?: boolean;
  notNull?: boolean;
  unsigned?: boolean;
  increment?: boolean;
  /** enum values. */
  values?: string[];
  metadata?: Metadata;
}
